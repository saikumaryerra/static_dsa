/**
 * `Document` — the document shell and single head hub for every page (spec §8,
 * §14; M5 architecture §2), ported from the head of `BaseLayout.astro`
 * (React migration, D-04).
 *
 * Pages never write their own `<title>`/`<meta>`: the layout records a
 * `PageMeta` (`usePageMeta`) during the body render, and this component emits
 * every head tag ONCE from it, after the body has rendered. The body arrives
 * as an HTML string (the first render pass) and is injected verbatim.
 *
 * What the head carries, in the legacy order: charset, viewport, the two
 * media-scoped theme-colors, the two font preloads, the pre-paint theme
 * script, title, description, canonical, icons, Open Graph and Twitter tags,
 * the page's JSON-LD or `noindex`, the theme toggle's `<noscript>`
 * kill-switch, then the site stylesheet and the page's module scripts. React
 * hoists `<title>` and the `<link>`/`<meta>` tags ahead of the inline script
 * when it serializes a document; the script still runs before anything in
 * `<body>` paints, which is the only order it depends on.
 *
 * Dropped from the legacy head (D-11): `<meta name="generator">` (Astro's) and
 * the maintainer HTML comments, which Astro shipped verbatim on every page.
 */
import type { JSX } from 'react';
import { deploymentUrl } from '../lib/deployment-url';
import type { PageMeta } from './context';
// The designer handoff's pre-paint theme script, BYTE-VERBATIM (it is listed in
// .prettierignore and relaxed in eslint.config.mjs to keep it that way): it
// must run before any content paints so the page never flashes the wrong
// theme. Mirrors src/lib/theme.ts#resolveTheme — keep the two in sync.
import prePaint from './pre-paint.inline.js?raw';

/** Where a page's built (or dev) assets live. */
export interface PageAssets {
  /** `href` of the site stylesheet. */
  stylesheet: string;
  /** `src` of a client module, by name (`src/client/modules/<name>.ts`). */
  module(name: string): string;
  /** `src` of the island bootstrap (`src/client/islands.ts`). */
  islands: string;
}

/** Props of `Document`. */
export interface DocumentProps {
  /** The page's recorded metadata. */
  meta: PageMeta;
  /** The page's own path (the canonical's default). */
  pathname: string;
  /** The deployment URL (`src/render/site-url.ts`). */
  site: string;
  /** Client modules the body asked for, in first-registration order. */
  modules: readonly string[];
  /** Whether the body hosts at least one island. */
  hasIslands: boolean;
  /** Asset URLs. */
  assets: PageAssets;
  /** The rendered body. */
  body: string;
}

/**
 * Without JS the CSS prefers-color-scheme fallback themes the page, so the
 * theme toggle would be a dead control — hide it (designer spec: no-JS
 * behaviour). `!important`: a noscript kill-switch must be unbeatable by the
 * stylesheet's equal-specificity `.theme-toggle { display: inline-flex }`
 * (QA DEFECT-1). Byte-identical to the legacy head's block.
 */
const THEME_TOGGLE_NOSCRIPT = `<style>
        /* !important: this <style> sits in <head> BEFORE Astro's injected
           stylesheet link, so the bundle's equal-specificity \`.theme-toggle
           { display: inline-flex }\` would otherwise win on source order. A
           noscript kill-switch must be unbeatable (QA DEFECT-1). */
        .theme-toggle {
          display: none !important;
        }
      </style>`;

/**
 * The whole document for one page.
 *
 * @param props - See `DocumentProps`.
 * @returns `<html>`.
 */
export function Document({
  meta,
  pathname,
  site,
  modules,
  hasIslands,
  assets,
  body,
}: DocumentProps): JSX.Element {
  const {
    title,
    description,
    canonicalPath,
    ogType = 'website',
    // SPEC-GAP (arch §5): §14 "OG images" is satisfied dependency-free by one
    // static 1200×630 default, generated by `npm run og` (scripts/build-og.mjs;
    // manual, deliberately NOT part of `npm run build`) from the REAL
    // renderer's `renderStatic()` output. Edit the script, never its outputs.
    ogImage = '/og-default.png',
    jsonLd,
    noindex = false,
  } = meta;
  // §14 requires absolute canonical URLs; `canonicalPath` lets a page override
  // the self-referential default (e.g. 404 → "/"). Joined by `deploymentUrl`,
  // which also normalizes `index.html` and the trailing slash.
  const canonical = deploymentUrl(site, canonicalPath ?? pathname);
  const ogImageUrl = deploymentUrl(site, ogImage);
  return (
    <html lang="en">
      <head>
        <meta charSet="utf-8" />
        <meta name="viewport" content="width=device-width, initial-scale=1" />
        {/* M7.1 THM-1: browser chrome matches the canvas (--bg per theme).
            Media-scoped so it works with JS off; ThemeToggle inserts an
            un-scoped meta AHEAD of these when the user overrides the OS and
            carries the same two literals, so the three sites change together. */}
        <meta
          name="theme-color"
          media="(prefers-color-scheme: light)"
          content="#FCFCFB"
        />
        <meta
          name="theme-color"
          media="(prefers-color-scheme: dark)"
          content="#0E0F12"
        />
        {/* Both self-hosted subsets, ahead of the stylesheet, so the fetch
            starts on the first byte rather than after the CSS discovers the
            @font-face. `crossorigin` is mandatory even same-origin — font
            requests are CORS-mode, and without it the preload is wasted. */}
        <link
          rel="preload"
          href="/fonts/plex-sans.woff2"
          as="font"
          type="font/woff2"
          crossOrigin=""
        />
        <link
          rel="preload"
          href="/fonts/plex-mono.woff2"
          as="font"
          type="font/woff2"
          crossOrigin=""
        />
        <script dangerouslySetInnerHTML={{ __html: prePaint }} />
        <title>{title}</title>
        <meta name="description" content={description} />
        <link rel="canonical" href={canonical} />
        {/* M7.1 ICO-1: raster fallbacks for the SVG mark, 32px PNG first for
            browsers without SVG favicons; both PNGs are rasterized from
            public/favicon.svg by `npm run icons`, never redrawn by hand. */}
        <link
          rel="icon"
          href="/favicon-32.png"
          type="image/png"
          sizes="32x32"
        />
        <link rel="icon" href="/favicon.svg" type="image/svg+xml" />
        <link rel="apple-touch-icon" href="/apple-touch-icon.png" />
        <meta property="og:type" content={ogType} />
        <meta property="og:site_name" content="LearnDSA" />
        <meta property="og:title" content={title} />
        <meta property="og:description" content={description} />
        <meta property="og:url" content={canonical} />
        <meta property="og:image" content={ogImageUrl} />
        <meta name="twitter:card" content="summary_large_image" />
        <meta name="twitter:title" content={title} />
        <meta name="twitter:description" content={description} />
        <meta name="twitter:image" content={ogImageUrl} />
        {jsonLd !== undefined && (
          <script
            type="application/ld+json"
            dangerouslySetInnerHTML={{ __html: jsonLd }}
          />
        )}
        {noindex && <meta name="robots" content="noindex" />}
        <noscript dangerouslySetInnerHTML={{ __html: THEME_TOGGLE_NOSCRIPT }} />
        <link rel="stylesheet" href={assets.stylesheet} />
        {modules.map((name) => (
          <script key={name} type="module" src={assets.module(name)} />
        ))}
        {hasIslands && <script type="module" src={assets.islands} />}
      </head>
      <body dangerouslySetInnerHTML={{ __html: body }} />
    </html>
  );
}
